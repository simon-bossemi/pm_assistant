const assert=require('node:assert/strict');
const report=require('./dist/ai-report.json');
const history=require('./dist/jira-history.json');
const controls=require('./dist/doc-controls.json');
const source=require('./dist/source.json');
const monitor=require('./dist/monitor.json');
const keys=new Set([...source.rows,...source.docRows].map(r=>r.key).filter(Boolean));
assert.equal(keys.size,history.issues.length);
assert.equal(monitor.total,keys.size);
assert.equal(report.sourceObservedAt,history.observedAt);
assert.equal(report.documentation.pairs,controls.pairs.length);
assert.equal(report.documentation.reviewActions,controls.pairs.filter(p=>p.reviewControl?.action).length);
assert.equal(report.sections.find(s=>s.name==='Host SW').tickets,37);
assert.equal(report.sections.find(s=>s.name==='AI Model Dev. Tools for Eagle N').tickets,19);
assert.match(report.overall,/emulator validation due dates/);
assert.match(report.limitations,/targets/);
assert.ok(report.attention.some(item=>item.includes('review')));
assert.ok(!JSON.stringify(report).includes('filter 19455'));
console.log('PASS: management report uses the current Jira capture, both workbook tabs, corrected review controls, and explicit date limits.');
